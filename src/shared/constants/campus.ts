/** 검색어가 학교 이름이나 별칭에 들어 있는지. 대소문자와 띄어쓰기는 가리지 않는다. */
export function campusMatches(campus: string, keyword: string): boolean {
  const flat = (s: string) => s.replace(/\s/g, "").toLowerCase();
  const k = flat(keyword);
  return [campus, ...(CAMPUS_ALIASES[campus] ?? [])].some((name) => flat(name).includes(k));
}

/** 캠퍼스가 속한 지역을 찾는다. 저장된 값을 화면에 다시 그릴 때 쓴다. */
export function regionOf(campus: string): Region | undefined {
  return REGIONS.find((region) =>
    (CAMPUSES_BY_REGION[region] as readonly string[]).includes(campus),
  );
}

export function isCampus(value: string): value is Campus {
  return (CAMPUSES as readonly string[]).includes(value);
}

