/**
 * 학과가 어느 계열인지 추정한다.
 *
 * 특성 학과까지 전부 계열을 손으로 적는 것은 유지가 안 된다.
 * 이름에 드러나는 단서로 나누고, 걸리지 않으면 '사회'로 둔다
 * (자유전공·국제학부처럼 계열이 모호한 것들이 여기 모인다).
 */
export function fieldOf(major: string): MajorField {
  for (const field of MAJOR_FIELDS) {
    if ((COMMON_MAJORS[field] as readonly string[]).includes(major)) return field;
  }

  if (/의예|치의|한의|약학|간호|수의|보건|바이오|생명|식품|물리치료/.test(major))
    return "의약·생명";
  if (/공학|소프트웨어|컴퓨터|인공지능|반도체|정보보호|시스템|기계|자동차|항공우주|조선/.test(major))
    return "공학";
  if (/교육과|교육학/.test(major)) return "사범";
  if (/디자인|미술|음악|체육|영화|무용|예술|패션|조형|도예|섬유/.test(major))
    return "예체능";
  if (/경영|경제|무역|금융|회계|세무|물류|부동산/.test(major)) return "상경";
  if (/어과|어문|문학|사학|철학|신학|불교|언어/.test(major)) return "인문";
  if (/과학|수학|물리|화학|천문|산림|농업|해양|축산/.test(major)) return "자연";

  return "사회";
}
